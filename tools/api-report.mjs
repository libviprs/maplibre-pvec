// Builds the API report of every public entry from the emitted declarations.
//   node tools/api-report.mjs          print it
//   node tools/api-report.mjs --write  rewrite etc/maplibre-pvec.api.md
// The tests regenerate it and fail on any difference, so a surface change is always a visible diff.
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

export const ENTRIES = {
  ".": "src/index.ts",
  "./style": "src/style/index.ts",
  "./text": "src/text/index.ts",
  "./hatch": "src/hatch/index.ts",
};

function statementNames(st) {
  if (ts.isVariableStatement(st)) return st.declarationList.declarations.map((d) => d.name.getText());
  if (st.name) return [st.name.getText()];
  return [];
}

export function buildApiReport(root) {
  const cfg = ts.readConfigFile(path.join(root, "tsconfig.build.json"), ts.sys.readFile);
  const parsed = ts.parseJsonConfigFileContent(cfg.config, ts.sys, root);
  const outDir = path.join(root, "__dts__");
  const options = { ...parsed.options, noEmit: false, declaration: true, emitDeclarationOnly: true, outDir, rootDir: path.join(root, "src") };
  const files = Object.values(ENTRIES).map((f) => path.join(root, f));
  const program = ts.createProgram(files, options);
  const emitted = new Map();
  program.emit(undefined, (f, text) => emitted.set(path.resolve(f), text), undefined, true);
  const checker = program.getTypeChecker();
  const entries = {};
  const out = ["# API report: maplibre-pvec", "", "Generated by `node tools/api-report.mjs --write`. Do not edit by hand.", ""];
  for (const [entry, file] of Object.entries(ENTRIES)) {
    const sf = program.getSourceFile(path.join(root, file));
    const mod = checker.getSymbolAtLocation(sf);
    const names = { values: [], types: [] };
    out.push(`## Entry \`${entry}\``, "");
    const syms = checker.getExportsOfModule(mod).sort((a, b) => a.name.localeCompare(b.name));
    for (const s of syms) {
      const real = s.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(s) : s;
      const decl = real.declarations?.[0];
      if (!decl) continue;
      const isValue = (real.flags & ts.SymbolFlags.Value) !== 0;
      (isValue ? names.values : names.types).push(s.name);
      const rel = path.relative(path.join(root, "src"), decl.getSourceFile().fileName).replace(/\.ts$/, ".d.ts");
      const dts = emitted.get(path.join(outDir, rel));
      const dsf = ts.createSourceFile("x.d.ts", dts, ts.ScriptTarget.ES2022, true);
      const stmts = dsf.statements.filter((st) => statementNames(st).includes(real.name));
      out.push(`### ${s.name}`, "", "```ts", ...stmts.map((st) => st.getFullText(dsf).trim().replace(/^ {4}/gm, "")), "```", "");
    }
    entries[entry] = { values: names.values, types: names.types };
  }
  return { entries, text: out.join("\n").replace(/\n+$/, "\n") };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
  const { text } = buildApiReport(root);
  if (process.argv.includes("--write")) {
    mkdirSync(path.join(root, "etc"), { recursive: true });
    writeFileSync(path.join(root, "etc/maplibre-pvec.api.md"), text);
  } else process.stdout.write(text);
}
