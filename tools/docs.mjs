function apiReference(root) {
  const report = readFileSync(path.join(root, "etc/maplibre-pvec.api.md"), "utf8");
  const out = [`${GEN("etc/maplibre-pvec.api.md")}# API reference\n`, "Declarations as emitted from the sources; the one-line notes are the doc comments. The frozen set is pinned by `release/v1-freeze.json`. Names are listed in [public surface](public-surface.md) too, which says what is deliberately not exported.\n"];
  for (const entry of report.split(/^## Entry /m).slice(1)) {
    const name = entry.match(/^`([^`]+)`/)[1];
    out.push(`## Entry \`${name}\`\n`);
    for (const sym of entry.split(/^### /m).slice(1)) {
      const id = sym.split("\n", 1)[0].trim();
      const code = sym.match(/```ts\n([\s\S]*?)```/)?.[1] ?? "";
      const lines = code.split("\n");
      const doc = lines.filter((l) => /^\/\*\* .* \*\/$/.test(l)).map((l) => l.slice(4, -3))[0];
      out.push(`### \`${id}\`\n`);
      if (doc) out.push(`${doc}\n`);
      out.push("```ts\n" + lines.filter((l) => !/^\s*private /.test(l)).join("\n").trimEnd() + "\n```\n");
    }
  }
  return out.join("\n");
}

