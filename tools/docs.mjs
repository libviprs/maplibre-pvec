function adrIndex(root) {
  const dir = path.join(root, "docs/adr");
  const rows = readdirSync(dir).filter((f) => /^\d{4}-.*\.md$/.test(f)).sort().map((f) => {
    const t = readFileSync(path.join(dir, f), "utf8");
    const title = t.match(/^# ADR (\d{4}): (.*)$/m);
    const status = t.match(/^- Status: (.*)$/m)?.[1] ?? "";
    const evidence = t.match(/^- Evidence: (.*)$/m)?.[1] ?? "";
    return `| [${title[1]}](${f}) | ${title[2]} | ${status} | ${evidence} |`;
  });
  return `${GEN("docs/adr/*.md")}# Architecture decision records (browser)

Eight ADRs freeze the phase 1 decisions. Each one quotes numbers from a spike report under \`docs/spikes/\`. Later records (0009 and up) decide what came after, and say what they measured in their own evidence.

| ADR | Subject | Status | Evidence |
|---|---|---|---|
${rows.join("\n")}

One more record, [WebGPU stays experimental behind a flag](webgpu-deferral.md), grew out of ADR 0008 when the flag was built.

## Phase 1 exit criterion

No phase 3 or phase 5 implementation lands before these eight are merged. Anything an ADR marks provisional is a tuning value the plan defers to phase 8 (\`M8.6\`), not a frozen number.

## Reading the numbers

Every spike ran in a throw-away container with software GL (SwiftShader for Chromium), so absolute frame times are relative costs between strategies, not GPU timings. Each report says which engine, version and platform produced a number. Where a spike needed something that does not exist yet (the \`pvec\` evaluator as WASM, a Tier 0 stream) the gap is written down in [deferred work](../deferred.md) and the ADR that depends on it says so.
`;
}

function apiReference(root) {
  const report = readFileSync(path.join(root, "etc/maplibre-pvec.api.md"), "utf8");
  const out = [`${GEN("etc/maplibre-pvec.api.md")}# API reference\n`, "Declarations as emitted from the sources; the one-line notes are the doc comments. The frozen set is pinned by `release/v1-freeze.json`. Names are listed in [public surface](public-surface.md) too, which says what is deliberately not exported.\n"];
  for (const entry of report.split(/^## Entry /m).slice(1)) {
    const name = entry.match(/^`([^`]+)`/)[1];
    out.push(`## Entry \`${name}\`\n`);
    for (const sym of entry.split(/^### /m).slice(1)) {
      const id = sym.split("\n", 1)[0].trim();
      const code = sym.match(/```ts\n([\s\S]*?)```/)?.[1] ?? "";
      const lines = code.split("\n");
      const doc = lines.filter((l) => /^\/\*\* .* \*\/$/.test(l)).map((l) => l.slice(4, -3))[0];
      out.push(`### \`${id}\`\n`);
      if (doc) out.push(`${doc}\n`);
      out.push("```ts\n" + lines.filter((l) => !/^\s*private /.test(l)).join("\n").trimEnd() + "\n```\n");
    }
  }
  return out.join("\n");
}

