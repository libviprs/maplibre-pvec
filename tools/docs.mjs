export function listDocPages(root = root0) {
  const out = [];
  const walk = (dir) => {
    for (const e of readdirSync(path.join(root, "docs", dir), { withFileTypes: true })) {
      const rel = path.posix.join(dir, e.name);
      if (e.isDirectory()) walk(rel);
      else if (e.name.endsWith(".md")) out.push(rel);
    }
  };
  walk("");
  return out.sort();
}

const GEN = (src) => `<!-- Generated by tools/docs.mjs from ${src}. Do not edit. -->\n`;
const fmt = (n) => (Number.isInteger(n) ? String(n) : n.toFixed(1));

function adrIndex(root) {
  const dir = path.join(root, "docs/adr");
  const rows = readdirSync(dir).filter((f) => /^\d{4}-.*\.md$/.test(f)).sort().map((f) => {
    const t = readFileSync(path.join(dir, f), "utf8");
    const title = t.match(/^# ADR (\d{4}): (.*)$/m);
    const status = t.match(/^- Status: (.*)$/m)?.[1] ?? "";
    const evidence = t.match(/^- Evidence: (.*)$/m)?.[1] ?? "";
    return `| [${title[1]}](${f}) | ${title[2]} | ${status} | ${evidence} |`;
  });
  return `${GEN("docs/adr/*.md")}# Architecture decision records (browser)

Eight ADRs freeze the phase 1 decisions. Each one quotes numbers from a spike report under \`docs/spikes/\`.

| ADR | Subject | Status | Evidence |
|---|---|---|---|
${rows.join("\n")}

One more record, [WebGPU stays experimental behind a flag](webgpu-deferral.md), grew out of ADR 0008 when the flag was built.

## Phase 1 exit criterion

No phase 3 or phase 5 implementation lands before these eight are merged. Anything an ADR marks provisional is a tuning value the plan defers to phase 8 (\`M8.6\`), not a frozen number.

## Reading the numbers

Every spike ran in a throw-away container with software GL (SwiftShader for Chromium), so absolute frame times are relative costs between strategies, not GPU timings. Each report says which engine, version and platform produced a number. Where a spike needed something that does not exist yet (the \`pvec\` evaluator as WASM, a Tier 0 stream) the gap is written down in [deferred work](../deferred.md) and the ADR that depends on it says so.
`;
}

function apiReference(root) {
  const report = readFileSync(path.join(root, "etc/maplibre-pvec.api.md"), "utf8");
  const out = [`${GEN("etc/maplibre-pvec.api.md")}# API reference\n`, "Declarations as emitted from the sources; the one-line notes are the doc comments. The frozen set is pinned by `release/v1-freeze.json`. Names are listed in [public surface](public-surface.md) too, which says what is deliberately not exported.\n"];
  for (const entry of report.split(/^## Entry /m).slice(1)) {
    const name = entry.match(/^`([^`]+)`/)[1];
    out.push(`## Entry \`${name}\`\n`);
    for (const sym of entry.split(/^### /m).slice(1)) {
      const id = sym.split("\n", 1)[0].trim();
      const code = sym.match(/```ts\n([\s\S]*?)```/)?.[1] ?? "";
      const lines = code.split("\n");
      const doc = lines.filter((l) => /^\/\*\* .* \*\/$/.test(l)).map((l) => l.slice(4, -3))[0];
      out.push(`### \`${id}\`\n`);
      if (doc) out.push(`${doc}\n`);
      out.push("```ts\n" + lines.filter((l) => !/^\s*private /.test(l)).join("\n").trimEnd() + "\n```\n");
    }
  }
  return out.join("\n");
}

function results(root) {
  const dir = path.join(root, "bench/results");
  return readdirSync(dir).filter((f) => f.endsWith(".json")).sort().map((f) => ({ file: `bench/results/${f}`, r: JSON.parse(readFileSync(path.join(dir, f), "utf8")) }));
}

function benchmarkReport(root) {
  const corpusPin = JSON.parse(readFileSync(path.join(root, "bench/corpus/corpus.json"), "utf8")).revision;
  const out = [`${GEN("bench/results/*.json, bench/baselines/renderer-baselines.json")}# Benchmark report\n`];
  out.push("These are display-fidelity and frame-behaviour measurements of the benchmark subject named under each result. They are not claims about geometric accuracy; the mathematical tolerances belong to the shared numeric policy (libviprs/pvec#1, P1.2), and this report cites none.\n");
  for (const { file, r } of results(root)) {
    out.push(`## ${file}\n`);
    out.push(`- commit \`${r.commit}\`, ${r.date}`);
    out.push(`- platform: ${r.environment.platform} (${/arm64/.test(r.environment.platform) ? "arm64 container" : "native x86_64"}), ${r.environment.cpu}`);
    out.push(`- browser: ${r.environment.browser} ${r.environment.browserVersion}, renderer ${r.environment.gpuRenderer}${r.environment.softwareRenderer ? " (software)" : ""}`);
    out.push(`- subject: ${r.subject}`);
    out.push(`- run-to-run variance limit ${r.variance.limit}, ${r.variance.ok ? "within the limit" : "over the limit: " + r.variance.failures.join(", ")}`);
    out.push(`- denied hosts reached: ${r.deniedHosts.length}\n`);
    out.push("| corpus case | metric | value | baseline | threshold |", "|---|---|---|---|---|");
    for (const m of r.metrics) {
      const th = m.threshold.op === "info" ? "none (recorded only)" : `${m.threshold.op} ${m.threshold.limit}`;
      out.push(`| ${corpusPin}/${m.case} | ${m.name} | ${fmt(m.value)} | ${fmt(m.baseline)} | ${th} |`);
    }
    out.push("");
  }
  out.push("The runs above used software GL, so they are relative costs.\n");
  const hwFile = path.join(root, "bench/baselines/renderer-baselines.json");
  const hw = JSON.parse(readFileSync(hwFile, "utf8"));
  out.push("## Real hardware (renderer-keyed baselines)\n");
  out.push("Stroke pipeline through the buffer pool, 1e6 segments per frame as ten 100k-segment ranges (ten draw calls), 1600x1000 css px at dpr 2, 60 s of rAF frames after a 3 s warm-up. Each row comes from the result file named in its last column; the pixel hash of the fixed snapshot scene is stored per renderer in `bench/baselines/renderer-baselines.json`. The CPU column is JavaScript submit time per frame; the GPU column is the timer-query time where the engine offers one. A 120 Hz display makes the frame interval 8.3 ms, so the interval is capped by the display, not by the work.\n");
  out.push("| renderer | engine | arch | frame p50/p95/max (ms) | frames over 20 ms | draw calls | CPU submit p95 (ms) | GPU frame p50 (ms) | 1e6 sync draw p50 (ms) | 1e6 upload (ms) | 4 MiB upload p95 (ms) | 8 MiB upload p95 (ms) | source |", "|---|---|---|---|---|---|---|---|---|---|---|---|---|");
  for (const [key, e] of Object.entries(hw.entries)) {
    const up = (b) => fmt(e.upload.find((u) => u.bytes === b).p95Ms);
    out.push(`| ${key.split(" | ")[0]} | ${e.engine} ${e.browserVersion} | ${e.arch} | ${fmt(e.frames.p50Ms)} / ${fmt(e.frames.p95Ms)} / ${fmt(e.frames.maxMs)} | ${e.frames.over20Ms} of ${e.frames.count} | ${e.drawCalls.perFrame} | ${fmt(e.cpu.submitP95Ms)} | ${e.gpu ? fmt(e.gpu.frameP50Ms) : "no timer query"} | ${fmt(e.draw1e6.syncDrawP50Ms)} | ${fmt(e.draw1e6.uploadMs)} | ${up(4 << 20)} | ${up(8 << 20)} | \`${e.source}\` |`);
  }
  out.push("");
  return out.join("\n");
}

function sloPage(root) {
  const out = [`${GEN("bench/results/*.json")}# First-useful-drawing marks\n`];
  out.push("First useful drawing is the time from navigation start to the first frame that shows geometry. The table is the baseline: a MapLibre map without the add-on, so the add-on has a number to be compared against. The add-on's own mark needs the remote source with real `.pvec` bytes and is not measured yet (see [deferred work](deferred.md), issue 50). The mark is therefore not claimed.\n");
  const last = results(root).at(-1);
  if (last) {
    out.push(`From \`${last.file}\` (${last.r.environment.platform}, ${last.r.environment.browser} ${last.r.environment.browserVersion}, software GL):\n`);
    out.push("| corpus case | median first useful drawing (ms) | threshold |", "|---|---|---|");
    for (const m of last.r.metrics.filter((x) => x.name === "first_useful_drawing_ms.median")) {
      out.push(`| ${m.case} | ${fmt(m.value)} | ${m.threshold.op === "info" ? "none (recorded only)" : m.threshold.op + " " + m.threshold.limit} |`);
    }
  }
  out.push("");
  return out.join("\n");
}

function docsIndex(root) {
  const all = listDocPages(root);
  const out = [`${GEN("tools/docs.mjs (PAGES) and the files under docs/")}# Documentation\n`];
  out.push("One page per subject. Pages marked generated are rebuilt by `node tools/docs.mjs --write` from the sources and committed results, and a test fails on any hand edit. Conformance classes are EPIC P's and evidence classes EPIC O's; these pages cite them and do not restate them.\n");
  const groups = [...new Set(PAGES.map((p) => p.group))];
  for (const g of groups) {
    if (g === "Decisions") {
      out.push(`## ${g}\n`, "- [ADR index](adr/README.md)");
      for (const p of PAGES.filter((x) => x.group === g)) out.push(`- [${p.title}](${p.path})`);
      out.push("");
      continue;
    }
    out.push(`## ${g}\n`);
    for (const p of PAGES.filter((x) => x.group === g)) out.push(`- [${p.title}](${p.path})`);
    if (g === "Using it") out.push("- [Examples](../examples/README.md)");
    out.push("");
  }
  const known = new Set(["README.md", "adr/README.md", ...PAGES.map((p) => p.path)]);
  out.push("## Decision records and spike reports\n");
  for (const f of all.filter((x) => /^adr\/\d{4}/.test(x))) out.push(`- [${f.slice(4, -3)}](${f})`);
  for (const f of all.filter((x) => x.startsWith("spikes/"))) out.push(`- [${f.slice(7, -3)}](${f})`);
  const rest = all.filter((x) => !known.has(x) && !/^adr\/\d{4}/.test(x) && !x.startsWith("spikes/"));
  for (const f of rest) out.push(`- [${f}](${f})`);
  out.push("");
  return out.join("\n");
}

export function generateDocs(root = root0) {
  return new Map([
    ["docs/adr/README.md", adrIndex(root)],
    ["docs/api/reference.md", apiReference(root)],
    ["docs/benchmark-report.md", benchmarkReport(root)],
    ["docs/slo.md", sloPage(root)],
    ["docs/README.md", docsIndex(root)],
  ]);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const mode = process.argv[2];
  let bad = 0;
  for (const [file, text] of generateDocs(root0)) {
    if (mode === "--write") writeFileSync(path.join(root0, file), text);
    else if (readFileSync(path.join(root0, file), "utf8") !== text) { console.error(`${file} differs from its sources`); bad = 1; }
  }
  process.exit(mode === "--write" || mode === "--check" ? bad : 2);
}
