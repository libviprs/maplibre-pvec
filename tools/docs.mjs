export function listDocPages(root = root0) {
  const out = [];
  const walk = (dir) => {
    for (const e of readdirSync(path.join(root, "docs", dir), { withFileTypes: true })) {
      const rel = path.posix.join(dir, e.name);
      if (e.isDirectory()) walk(rel);
      else if (e.name.endsWith(".md")) out.push(rel);
    }
  };
  walk("");
  return out.sort();
}

