const fr = (n) => (n === null || n === undefined ? "n/a" : n.toFixed(2));
const kb = (n) => (n >= 1e6 ? `${(n / 1e6).toFixed(2)} MB` : n >= 1e3 ? `${(n / 1e3).toFixed(1)} kB` : `${n} B`);

/** The real evaluator and real container numbers from spikes/pvec-real, when they have been run. */
function realEvaluatorSection(root) {
  const file = path.join(root, "spikes/pvec-real/results.json");
  if (!existsSync(file)) return [];
  const r = JSON.parse(readFileSync(file, "utf8"));
  const out = ["## Real pvec evaluator and real .pvec bytes\n"];
  out.push(`- \`spikes/pvec-real/results.json\`: ${r.browser}, ${r.platform} container, \`libviprs/pvec\` \`${r.pvecCommit.slice(0, 7)}\`, ABI version ${r.abiVersion}`);
  out.push(`- module ${r.wasmBytes} bytes, compile ${fmt(r.compileMs)} ms, instantiate ${fmt(r.instantiateMs)} ms`);
  out.push("- the docker host was shared and loaded while this ran, so every time here is an upper bound and only the shape is a result");
  out.push("- the subject is the shipped evaluator through the packed binding; the arrays are views over linear memory, nothing is copied\n");
  out.push("### Evaluation cost per named fixture\n");
  out.push("One evaluation is a batch of the fixture's entities tessellated to a drawing-sized budget, including the four views and the release. Per vertex is at a budget chosen to give about that many vertices from one curve (n/a: the fixture has fewer vertices than that at any budget).\n");
  out.push("| fixture | entities | one evaluation (ns) | vertices | ns/vertex at 1e2 | 1e3 | 1e4 | 1e5 |", "|---|---|---|---|---|---|---|---|");
  for (const f of r.fixtures) {
    const cell = (n) => { const a = f.amortised.find((x) => x.targetVertices === n); return a && a.nsPerVertex !== undefined ? fmt(a.nsPerVertex) : "n/a"; };
    out.push(`| ${f.id} | ${f.entities} | ${fmt(Math.round(f.singleEvaluation.medianNsPerCall))} | ${f.singleEvaluation.vertices} | ${cell(1e2)} | ${cell(1e3)} | ${cell(1e4)} | ${cell(1e5)} |`);
  }
  out.push("");
  if (r.large?.length) {
    out.push("### Packed output on the generated corpus entries\n");
    out.push("| entry | file | entities | open (ms) | whole drawing (ms) | ns/entity | ns/vertex | 25 percent window (ms) | 5 percent window (ms) | JS heap bytes/entity |", "|---|---|---|---|---|---|---|---|---|---|");
    for (const l of r.large) {
      const [full, q, sm] = l.viewports;
      out.push(`| ${l.id} | ${kb(l.fileBytes)} | ${l.entities} | ${fmt(l.openMs)} | ${fmt(full.f64.tessellateMs)} | ${fmt(full.f64.nsPerEntity)} | ${fmt(full.f64.nsPerVertex)} | ${fmt(q.f64.tessellateMs)} | ${fmt(sm.f64.tessellateMs)} | ${full.heap ? fr(full.heap.bytesPerEntity) : "n/a"} |`);
    }
    out.push("");
  }
  if (r.leak) out.push(`Leak check: ${r.leak.cycles} open, query, tessellate and release cycles left linear memory at ${r.leak.pagesAfter6000} pages (${r.leak.pagesBefore} before, ${r.leak.pagesAfterFirst3000} after the first half).\n`);
  if (r.previewAccounting?.length) {
    out.push("### Preview error accounting and viewport coverage\n");
    out.push("Measured is the largest distance between the preview and a reference tessellation at a hundred thousandth of the extent or tighter (both directions); declared is the budget asked for. The ratio is measured over declared. Coverage counts entities whose reference curve meets a window and are missing from the viewport batch.\n");
    out.push("| fixture | ratio at 1e-1 | 1e-2 | 1e-3 of extent | all within declared | windows | entities meeting a window | missing |", "|---|---|---|---|---|---|---|---|");
    const rows = [...r.previewAccounting, ...(r.previewAccountingLarge ?? [])];
    for (const a of rows) {
      const p = a.previews;
      const three = p.length === 3 ? p.map((x) => fr(x.ratio)) : ["", "", fr(p[0]?.ratio)];
      out.push(`| ${a.id} | ${three.join(" | ")} | ${p.every((x) => x.withinDeclared) ? "yes" : "NO"} | ${a.coverage.boxes} | ${a.coverage.entitiesMeetingBox} | ${a.coverage.missing} |`);
    }
    out.push("");
  }
  if (r.tier0Stream?.length) {
    out.push("### Tier 0 stream and spatial directory (ABI 2)\n");
    out.push("The files are the corpus entries written with a spatial directory and one Tier 0 block per leaf. Entries are what the stream returns for a window; uncovered is what `query_viewport` returns for it less the entries (the advanced curves, which are in no leaf, and every entity of a leaf with no Tier 0 block). Missing is entries plus uncovered less the entity count of the window, so 0 means the audit loses nothing. Previews are checked one way: every point of a tight reference tessellation of the curve is within the declared error of the preview polyline.\n");
    out.push("| entry | window (share of extent) | entities | entries | exact | previews | infeasible | uncovered | leaves read | missing |", "|---|---|---|---|---|---|---|---|---|---|");
    for (const t of r.tier0Stream) for (const w of t.windows) out.push(`| ${t.id} | ${w.fraction} | ${w.entities} | ${w.entries} | ${w.exact} | ${w.previews} | ${w.infeasible} | ${w.uncovered} | ${w.leavesRead} | ${w.missing} |`);
    out.push("");
    out.push("| entry | previews checked | worst measured over declared | all within declared |", "|---|---|---|---|");
    for (const t of r.tier0Stream) for (const p of t.previews) out.push(`| ${t.id} | ${p.entitiesChecked} | ${fr(p.worstMeasuredOverDeclared)} | ${p.withinDeclared ? "yes" : "NO"} |`);
    out.push("");
  }
  if (r.tier0Slices?.length) {
    out.push("### Tier 0 decoder slices on the real stream\n");
    out.push("The default cursor of the layer drained by `Tier0Decoder` with its default slice size. A slice is one `decodeSlice` call; the ceiling is `DEFAULTS.maxSliceMs`. Opening the file in the evaluator is the cursor's first step and is reported on its own.\n");
    out.push("| entry | entities | slices | open (ms) | max slice (ms) | median slice (ms) | total (ms) |", "|---|---|---|---|---|---|---|");
    for (const t of r.tier0Slices) out.push(`| ${t.id} | ${t.refused ? `refused: ${t.refused}` : t.entities} | ${t.slices} | ${fmt(t.openMs)} | ${fmt(t.maxSliceMs)} | ${fmt(t.medianSliceMs)} | ${fmt(t.totalMs)} |`);
    out.push("");
  }
  for (const [name, label] of [["x86_64", "x86_64"], ["arm64", "arm64"]]) {
    const rf = path.join(root, `spikes/pvec-real/range-results-${name}.json`);
    if (!existsSync(rf)) continue;
    const rr = JSON.parse(readFileSync(rf, "utf8"));
    out.push(`### Range bootstrap on real files, ${label}\n`);
    out.push(`\`spikes/pvec-real/range-results-${name}.json\`: ${rr.platform}. The production source and bootstrap against files from pvec's writer over a loopback range origin; the ceiling is ${rr.bootstrapMaxRequests} bootstrap requests. A window is a share of the extent around its centre; ranges are coalesced when adjacent.\n`);
    out.push("| file | bytes | blocks | RTT (ms) | bootstrap requests | bootstrap bytes | bootstrap (ms) | full: requests / bytes / ms | 25 percent: requests / bytes / ms | 5 percent: requests / bytes / ms |", "|---|---|---|---|---|---|---|---|---|---|");
    const show = new Set(["line-001", "nurbs-d3-001", "pathological-1e3", "architectural-1e5", "mep-1e5", "spline-heavy-1e5", "architectural-1e6"]);
    for (const x of rr.runs.filter((y) => show.has(y.name) && (y.rttMs === 0 || y.rttMs === 100))) {
      if (x.error) { out.push(`| ${x.name} | ${x.fileBytes} | | ${x.rttMs} | ${x.error} | | | | | |`); continue; }
      const v = (p) => { const w = x.viewports.find((q) => q.preset === p); return `${w.requests} / ${kb(w.bytes)} / ${fmt(w.ms)}`; };
      out.push(`| ${x.name} | ${kb(x.fileBytes)} | ${x.bootstrap.blocks} | ${x.rttMs} | ${x.bootstrap.requests} | ${kb(x.bootstrap.bytes)} | ${fmt(x.bootstrap.ms)} | ${v("fullExtent")} | ${v("quarter")} | ${v("small")} |`);
    }
    out.push("");
    const withDir = rr.runs.filter((y) => y.spatialDirectory && y.rttMs === 0 && !y.error);
    if (withDir.length) {
      out.push("With the spatial directory, a window reads the prefix, the directory and the hot blocks of the leaves it touches (bytes and share of the file):\n");
      out.push("| file | bytes | 25 percent window | 5 percent window |", "|---|---|---|---|");
      for (const x of withDir) {
        const c = (p) => { const w = x.viewports.find((q) => q.preset === p); return w?.spatial ? `${w.spatial.cells} cells, ${kb(w.spatial.bytes)} (${(100 * w.spatial.bytes / x.fileBytes).toFixed(1)}%)` : "n/a"; };
        out.push(`| ${x.name} | ${kb(x.fileBytes)} | ${c("quarter")} | ${c("small")} |`);
      }
      out.push("");
    }
  }
  return out;
}

function sloPage(root) {
  const out = [`${GEN("bench/results/*.json")}# First-useful-drawing marks\n`];
  out.push("First useful drawing is the time from navigation start to the first frame that shows geometry. The table is the baseline: a MapLibre map without the add-on, so the add-on has a number to be compared against. The add-on's own mark needs the remote source with real `.pvec` bytes and is not measured yet (see [deferred work](deferred.md), issue 50). The mark is therefore not claimed.\n");
  const last = results(root).at(-1);
  if (last) {
    out.push(`From \`${last.file}\` (${last.r.environment.platform}, ${last.r.environment.browser} ${last.r.environment.browserVersion}, software GL):\n`);
    out.push("| corpus case | median first useful drawing (ms) | threshold |", "|---|---|---|");
    for (const m of last.r.metrics.filter((x) => x.name === "first_useful_drawing_ms.median")) {
      out.push(`| ${m.case} | ${fmt(m.value)} | ${m.threshold.op === "info" ? "none (recorded only)" : m.threshold.op + " " + m.threshold.limit} |`);
    }
  }
  out.push("");
  return out.join("\n");
}

function docsIndex(root) {
  const all = listDocPages(root);
  const out = [`${GEN("tools/docs.mjs (PAGES) and the files under docs/")}# Documentation\n`];
  out.push("One page per subject. Pages marked generated are rebuilt by `node tools/docs.mjs --write` from the sources and committed results, and a test fails on any hand edit. Conformance classes are EPIC P's and evidence classes EPIC O's; these pages cite them and do not restate them.\n");
  const groups = [...new Set(PAGES.map((p) => p.group))];
  for (const g of groups) {
    if (g === "Decisions") {
      out.push(`## ${g}\n`, "- [ADR index](adr/README.md)");
      for (const p of PAGES.filter((x) => x.group === g)) out.push(`- [${p.title}](${p.path})`);
      out.push("");
      continue;
    }
    out.push(`## ${g}\n`);
    for (const p of PAGES.filter((x) => x.group === g)) out.push(`- [${p.title}](${p.path})`);
    if (g === "Using it") out.push("- [Examples](../examples/README.md)");
    out.push("");
  }
  const known = new Set(["README.md", "adr/README.md", ...PAGES.map((p) => p.path)]);
  out.push("## Decision records and spike reports\n");
  for (const f of all.filter((x) => /^adr\/\d{4}/.test(x))) out.push(`- [${f.slice(4, -3)}](${f})`);
  for (const f of all.filter((x) => x.startsWith("spikes/"))) out.push(`- [${f.slice(7, -3)}](${f})`);
  const rest = all.filter((x) => !known.has(x) && !/^adr\/\d{4}/.test(x) && !x.startsWith("spikes/"));
  for (const f of rest) out.push(`- [${f}](${f})`);
  out.push("");
  return out.join("\n");
}

export function generateDocs(root = root0) {
  return new Map([
    ["docs/adr/README.md", adrIndex(root)],
    ["docs/api/reference.md", apiReference(root)],
    ["docs/benchmark-report.md", benchmarkReport(root)],
    ["docs/slo.md", sloPage(root)],
    ["docs/README.md", docsIndex(root)],
  ]);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const mode = process.argv[2];
  let bad = 0;
  for (const [file, text] of generateDocs(root0)) {
    if (mode === "--write") writeFileSync(path.join(root0, file), text);
    else if (readFileSync(path.join(root0, file), "utf8") !== text) { console.error(`${file} differs from its sources`); bad = 1; }
  }
  process.exit(mode === "--write" || mode === "--check" ? bad : 2);
}
